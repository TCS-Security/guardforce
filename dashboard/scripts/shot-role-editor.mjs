import { chromium } from "@playwright/test";
const BASE = process.env.E2E_BASE_URL ?? "http://localhost:3000";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto(BASE + "/login");
await page.getByLabel("Email").fill("owner@sentinel.test");
await page.getByLabel("Password").fill("guardforce");
await page.getByRole("button", { name: "Sign in" }).click();
await page.waitForURL((url) => !url.pathname.startsWith("/login"));
await page.goto(BASE + "/settings/roles", { waitUntil: "domcontentloaded" });
await page.getByRole("button", { name: "Edit Supervisor" }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: "/tmp/shot-role-editor.png" });
await page.keyboard.press("Escape");
await page.goto(BASE + "/settings/team", { waitUntil: "domcontentloaded" });
await page.getByRole("button", { name: "Invite" }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: "/tmp/shot-invite.png" });
console.log("done");
await browser.close();
